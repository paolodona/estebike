#!/usr/bin/env node
/**
 * Post-download processing for /wa-gallery-pull.
 *
 * Scans ~/Downloads for `estebike_*.jpg` and `agonisti_*.jpg` files (produced
 * by the WhatsApp media-panel blob downloads), then:
 *   1. Hashes each file (MD5).
 *   2. Skips files whose hash is already in pull-state.json `known_hashes`
 *      (deletes the download).
 *   3. Skips intra-batch duplicates (same hash from both groups — keeps
 *      first occurrence, deletes the rest).
 *   4. Renames the kept files using the next sequential index in the target
 *      month folder, preserving the original sender/caption tail.
 *   5. Moves them to `public/images/gallery/YYYY/MM/`.
 *   6. Generates an Italian alt-text entry in `descriptions.json` for each
 *      new file (sender + activity, with basic profanity censoring).
 *   7. Updates `pull-state.json`: `last_pull`, `total_downloaded`,
 *      `known_hashes`, `months_with_images`, and per-group counts.
 *
 * Usage:
 *   node scripts/whatsapp-gallery/process-downloads.mjs [--month YYYY-MM] [--dry-run]
 *
 * Defaults to the current month. Run from the repo root.
 */
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import os from 'node:os';

const ROOT = process.cwd();
const STATE_PATH = path.join(ROOT, 'scripts/whatsapp-gallery/pull-state.json');
const DESC_PATH = path.join(ROOT, 'scripts/whatsapp-gallery/descriptions.json');
const DL = path.join(os.homedir(), 'Downloads');

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  if (i === -1) return fallback;
  return process.argv[i + 1];
}
const dryRun = process.argv.includes('--dry-run');
const now = new Date();
const defaultMonth = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`;
const month = arg('--month', defaultMonth);
const [year, mon] = month.split('-');
const DEST_DIR = path.join(ROOT, 'public/images/gallery', year, mon);

if (!fs.existsSync(STATE_PATH)) {
  console.error(`pull-state.json not found at ${STATE_PATH}`);
  process.exit(1);
}
if (!dryRun) fs.mkdirSync(DEST_DIR, { recursive: true });

const state = JSON.parse(fs.readFileSync(STATE_PATH, 'utf8'));
const known = new Set(state.known_hashes);
const desc = fs.existsSync(DESC_PATH)
  ? JSON.parse(fs.readFileSync(DESC_PATH, 'utf8'))
  : { _comment: 'Maps image filename to Italian alt text. Auto-generated by /wa-gallery-pull.' };

const files = fs
  .readdirSync(DL)
  .filter((f) => /^(estebike|agonisti)_\d+_.*\.jpg$/i.test(f) && !f.includes('('))
  .sort();

let maxIdx = 0;
if (fs.existsSync(DEST_DIR)) {
  for (const f of fs.readdirSync(DEST_DIR)) {
    const m = f.match(/^estebike_(\d+)_/);
    if (m) maxIdx = Math.max(maxIdx, parseInt(m[1], 10));
  }
}

const PROFANITY = /\b(cazzo|minchia|merda|stronz[oa]|vaffanculo|coglione|fuck|shit|damn|bitch)\b/gi;

function generateDescription(filename) {
  // Filename produced by extractor: estebike_NNN_<sender_caption>.jpg
  // The sender substring is alphanumeric (spaces -> _), max 20 chars,
  // optionally followed by caption text concatenated camelCase.
  const m = filename.match(/^estebike_\d+_(.+)\.jpg$/);
  if (!m) return 'Foto dal gruppo EsteBike';
  const tail = m[1];
  const parts = tail.split(/(?<=[a-z])(?=[A-Z])/);
  const sender = parts[0].replace(/_/g, ' ').trim();
  const phoneLike = /^\+?\d/.test(sender) || /^39\b/.test(sender);
  if (parts.length < 2) {
    if (phoneLike || sender.length === 0) return 'Foto dal gruppo EsteBike';
    return `${sender} - uscita in bici`;
  }
  let caption = parts.slice(1).join(' ').replace(/_/g, ' ').trim();
  caption = caption.charAt(0).toUpperCase() + caption.slice(1);
  caption = caption.replace(PROFANITY, '***');
  if (caption.length > 75) caption = caption.substring(0, 75).replace(/\s+\S*$/, '');
  return caption;
}

const seen = new Set();
const moved = [];
const skipped = { knownDup: 0, crossDup: 0 };
const newHashes = [];
const groupCounts = { estebike: 0, agonisti: 0 };
let censored = 0;

for (const f of files) {
  const buf = fs.readFileSync(path.join(DL, f));
  const hash = crypto.createHash('md5').update(buf).digest('hex');
  if (known.has(hash)) {
    skipped.knownDup++;
    if (!dryRun) fs.unlinkSync(path.join(DL, f));
    continue;
  }
  if (seen.has(hash)) {
    skipped.crossDup++;
    if (!dryRun) fs.unlinkSync(path.join(DL, f));
    continue;
  }
  seen.add(hash);
  newHashes.push(hash);
  const m = f.match(/^(estebike|agonisti)_\d+_(.+)\.jpg$/i);
  const tail = m ? m[2] : 'unknown';
  const group = m[1].toLowerCase();
  groupCounts[group]++;
  maxIdx++;
  const newName = `estebike_${String(maxIdx).padStart(3, '0')}_${tail}.jpg`;
  if (!dryRun) fs.renameSync(path.join(DL, f), path.join(DEST_DIR, newName));
  const description = generateDescription(newName);
  if (description.includes('***')) censored++;
  if (!desc[newName]) desc[newName] = description;
  moved.push({ from: f, to: newName, hash, description });
}

if (!dryRun && moved.length > 0) {
  state.known_hashes.push(...newHashes);
  state.total_downloaded += moved.length;
  state.last_pull = new Date().toISOString().replace(/\.\d+Z$/, 'Z');
  state.months_with_images[month] = (state.months_with_images[month] || 0) + moved.length;
  if (state.groups?.['Estebike']) {
    state.groups['Estebike'].last_pull = state.last_pull;
    state.groups['Estebike'].total_downloaded += groupCounts.estebike;
  }
  if (state.groups?.['AGONISTI TEAM Estebike']) {
    state.groups['AGONISTI TEAM Estebike'].last_pull = state.last_pull;
    state.groups['AGONISTI TEAM Estebike'].total_downloaded += groupCounts.agonisti;
  }
  fs.writeFileSync(STATE_PATH, JSON.stringify(state, null, 2));

  const _comment = desc._comment;
  delete desc._comment;
  const reordered = { _comment, ...desc };
  fs.writeFileSync(DESC_PATH, JSON.stringify(reordered, null, 2));
}

console.log(
  JSON.stringify(
    {
      dryRun,
      month,
      destDir: path.relative(ROOT, DEST_DIR),
      seen: files.length,
      moved: moved.length,
      groupCounts,
      skipped,
      censored,
      sample: moved.slice(0, 5).map((x) => ({ to: x.to, desc: x.description })),
    },
    null,
    2,
  ),
);
